-- Private schema: accessed exclusively by the Express backend, never by the Data API.
CREATE SCHEMA IF NOT EXISTS tarefas;
REVOKE ALL ON SCHEMA tarefas FROM PUBLIC;
CREATE TABLE IF NOT EXISTS tarefas.users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL, email TEXT NOT NULL UNIQUE, password_hash TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS tarefas.sessions (
  token_hash TEXT PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES tarefas.users(id) ON DELETE CASCADE,
  expires_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS tarefas.task_types (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES tarefas.users(id) ON DELETE CASCADE,
  name TEXT NOT NULL, color TEXT NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS task_types_user_name ON tarefas.task_types(user_id, lower(name));
CREATE TABLE IF NOT EXISTS tarefas.tasks (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL, category TEXT NOT NULL DEFAULT 'Pessoal',
  priority INTEGER NOT NULL DEFAULT 2 CHECK (priority IN (1, 2, 3)),
  due TEXT, due_time TEXT, done INTEGER NOT NULL DEFAULT 0 CHECK (done IN (0, 1)),
  created_at TEXT NOT NULL DEFAULT to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
  user_id INTEGER REFERENCES tarefas.users(id),
  type_id INTEGER REFERENCES tarefas.task_types(id),
  recurrence TEXT NOT NULL DEFAULT 'none' CHECK (recurrence IN ('none', 'daily')),
  recurrence_until TEXT
);
CREATE INDEX IF NOT EXISTS tasks_user_id ON tarefas.tasks(user_id);
CREATE TABLE IF NOT EXISTS tarefas.task_occurrences (
  task_id INTEGER NOT NULL REFERENCES tarefas.tasks(id) ON DELETE CASCADE,
  due TEXT NOT NULL,
  done INTEGER NOT NULL DEFAULT 0 CHECK (done IN (0, 1)),
  skipped INTEGER NOT NULL DEFAULT 0 CHECK (skipped IN (0, 1)),
  PRIMARY KEY (task_id, due)
);
ALTER TABLE tarefas.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE tarefas.sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE tarefas.task_types ENABLE ROW LEVEL SECURITY;
ALTER TABLE tarefas.tasks ENABLE ROW LEVEL SECURITY;
ALTER TABLE tarefas.task_occurrences ENABLE ROW LEVEL SECURITY;

CREATE TABLE IF NOT EXISTS tarefas.auth_attempts (
  key TEXT PRIMARY KEY, attempts INTEGER NOT NULL, expires_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS auth_attempts_expiry ON tarefas.auth_attempts(expires_at);
ALTER TABLE tarefas.auth_attempts ENABLE ROW LEVEL SECURITY;
